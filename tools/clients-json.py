#!/usr/bin/env python3
"""Write clients.json: the installations this launcher offers, and only the ones that run.

    python3 tools/clients-json.py                       # uses ~/devspace/WebMC/webmc-port
    python3 tools/clients-json.py --port /path/to/webmc-port --out clients.json

The list is measured, not curated. `webmc-port/site/routes.json` (written by that repository's
tools/route.py) decides playability from each version's *own* metadata - LWJGL 2 with Java 8 runs in a page,
LWJGL 3 needs a JavaScript LWJGL 3 nobody has written, a version newer than the Java the browser runtime has
cannot start - and this joins that with the clients the port has actually published, because a version that
is on the site is playable whatever a route file says about it.

Two kinds of installation come out of it:

  real-java   the official jar, in the page, under CheerpJ. Mods load at play time.
  compiled    a client compiled from the official one by the port's build jobs. Mods are baked in, so if a
              player wants their own, a build has to run - which is what the launcher's custom build does.

Versions the engine could build but has not built are listed separately, so the launcher can offer them
without pretending they exist.
"""

from __future__ import annotations

import argparse
import datetime
import json
import pathlib

PORT_DEFAULT = pathlib.Path.home() / "devspace" / "WebMC" / "webmc-port"
# This project supports up to 1.21.11. The 26.x line needs Java 25, which no browser runtime has, and listing a
# version the engine cannot run is worse than not listing it - so it is excluded here, once, for every list the
# launcher draws.
SUPPORTED = ("1.", "a", "b", "rd", "c", "in", "inf", "pre", "alpha", "beta",
             "13w", "14w", "15w", "16w", "17w", "18w")


def supported(version: str) -> bool:
    """Anything that is not a version this project runs: 26.x and later, and the odd non-version id."""
    text = str(version)
    return text.startswith(SUPPORTED) and not text.startswith("26.")
BASE = "https://amphibiandev.github.io/webmc-port"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--port", default=str(PORT_DEFAULT))
    parser.add_argument("--out", default="clients.json")
    parser.add_argument("--base", default=BASE)
    parser.add_argument("--build-service", default="",
                        help="the build worker's url (Cloudflare); a local service is only a fallback")
    args = parser.parse_args(argv)

    port = pathlib.Path(args.port).expanduser()
    routes_path = port / "site" / "routes.json"
    if not routes_path.is_file():
        print(f"{routes_path} is not there: run this where the port repository is, or pass --port")
        return 2
    routes = json.loads(routes_path.read_text())["versions"]
    state_path = port / "state.json"
    published = set(json.loads(state_path.read_text()).get("built", {})) if state_path.is_file() else set()

    installations, buildable = [], []
    for version, route in sorted(routes.items()):
        if not supported(version):
            continue
        compiled = route.get("route") == "aot"
        # a client that is on the site is playable, whatever the route file last recorded about it
        live = compiled and (version in published or route.get("playable"))
        if not (route.get("playable") or live):
            if compiled and route.get("bakes_mods"):
                buildable.append({"id": version, "why": route.get("why"), "engine": route.get("engine")})
            continue
        installations.append({
            "id": version,
            "kind": "compiled" if compiled else "real-java",
            "url": f"{args.base}/clients/{version}/" if compiled else f"{args.base}/play.html?version={version}",
            "java": route.get("java"),
            "lwjgl": route.get("lwjgl"),
            "why": route.get("why"),
            "mods": "baked at build time" if compiled else "at play time (real JVM)",
            "bakes": bool(route.get("bakes_mods")),
            "metadata": route.get("metadata"),
        })

    # newest compiled first, then the real-JVM versions oldest to newest: the order a player looks for
    installations.sort(key=lambda entry: (entry["kind"] != "compiled",
                                          _order(entry["id"]) if entry["kind"] != "compiled" else "",
                                          entry["id"]))
    buildable.sort(key=lambda entry: entry["id"], reverse=True)

    document = {
        "note": "Only versions a browser can run, generated by tools/clients-json.py from "
                "webmc-port/site/routes.json and the clients that repository has published.",
        "generated": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "counts": {
            "playable": len(installations),
            "compiled": sum(1 for entry in installations if entry["kind"] == "compiled"),
            "real_java": sum(1 for entry in installations if entry["kind"] == "real-java"),
            "buildable": len(buildable),
        },
        # Where a build is asked for. The worker (gateway/build-worker.js in the port) is how a *deployed*
        # page can start a bake: it holds the GitHub token and dispatches the workflow. A local service is a
        # development fallback and nothing more.
        "build": {
            "service": args.build_service,
            "fallback": "http://127.0.0.1:8787",
            "note": "POST a version and mods to <service>/api/build; poll <service>/api/build?id=…",
        },
        "installations": installations,
        "buildable": buildable,
    }
    pathlib.Path(args.out).write_text(json.dumps(document, indent=1) + "\n")
    print(f"{args.out}: {len(installations)} playable installation(s) "
          f"({document['counts']['compiled']} compiled, {document['counts']['real_java']} real Java), "
          f"{len(buildable)} buildable")
    return 0


def _order(version: str) -> tuple:
    """A sort key that puts 1.7.10 before 1.10, which a plain string sort does not."""
    parts = []
    for chunk in version.replace("_", ".").split("."):
        parts.append((0, int(chunk)) if chunk.isdigit() else (1, chunk))
    return tuple(parts)


if __name__ == "__main__":
    raise SystemExit(main())
